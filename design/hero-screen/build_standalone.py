"""Build standalone HTML pages from the canvas `.dc.html` artboards.

Usage: python3 build_standalone.py            # builds every *.dc.html here
       python3 build_standalone.py Main.dc.html

Each `.dc.html` needs the Design canvas runtime to render. This script wraps
the artboard's markup and logic class in a small built-in runtime (DC_LITE
below) that supports what these artboards use: {{holes}}, <sc-for>, <sc-if>,
<helmet>, onX event bindings, boolean `disabled`, and DCLogic state. Output
goes to standalone/<name>.html, which opens directly in any browser.
"""
import html
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / 'standalone'
NAMES = {'Main': 'hero-screen', 'Economy': 'economy', 'Scene': 'empire-scene'}
# Canvas asset urls -> local files, so standalone pages load images from the repo.
BLOBS = {'/_blob/6768cc2a309a0d730e40c3da529dbaae': '../../scene/townhall-pixellab.png'}

DC_LITE = r"""
(function () {
  const HOLE = /\{\{\s*([^}]+?)\s*\}\}/g;
  const WHOLE = /^\{\{\s*([^}]+?)\s*\}\}$/;
  const lookup = (path, scope) => {
    if (path === 'true') return true;
    if (path === 'false') return false;
    if (/^-?\d+(\.\d+)?$/.test(path)) return Number(path);
    return path.split('.').reduce((v, k) => (v == null ? undefined : v[k]), scope);
  };
  const text = (s, scope) => s.replace(HOLE, (_, p) => {
    const v = lookup(p, scope);
    return v == null ? '' : String(v);
  });

  function render(node, scope, out) {
    if (node.nodeType === Node.TEXT_NODE) {
      out.appendChild(document.createTextNode(text(node.nodeValue, scope)));
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    const tag = node.localName;
    if (tag === 'helmet') return;
    if (tag === 'sc-for') {
      const m = (node.getAttribute('list') || '').match(WHOLE);
      const list = m ? lookup(m[1], scope) || [] : [];
      const as = node.getAttribute('as') || 'item';
      list.forEach((item, i) => {
        const inner = Object.assign(Object.create(scope), { [as]: item, $index: i });
        node.childNodes.forEach((c) => render(c, inner, out));
      });
      return;
    }
    if (tag === 'sc-if') {
      const m = (node.getAttribute('value') || '').match(WHOLE);
      if (m && lookup(m[1], scope)) node.childNodes.forEach((c) => render(c, scope, out));
      return;
    }
    const el = node.cloneNode(false);
    for (const a of Array.from(el.attributes)) el.removeAttribute(a.name);
    for (const a of Array.from(node.attributes)) {
      const whole = a.value.match(WHOLE);
      if (a.name.startsWith('on')) {
        const fn = whole ? lookup(whole[1], scope) : null;
        if (typeof fn === 'function') el.addEventListener(a.name.slice(2), fn);
      } else if (a.name === 'disabled') {
        const v = whole ? lookup(whole[1], scope) : true;
        if (v) el.setAttribute('disabled', '');
      } else if (a.name.startsWith('hint-')) {
        // placeholder hints are only for the canvas editor
      } else {
        el.setAttribute(a.name, text(a.value, scope));
      }
    }
    const kids = node.localName === 'template' ? node.content.childNodes : node.childNodes;
    kids.forEach((c) => render(c, scope, el));
    out.appendChild(el);
  }

  window.DCLogic = class {
    constructor(props) { this.props = props || {}; this.state = {}; }
    setState(patch) {
      const next = typeof patch === 'function' ? patch(this.state) : patch;
      this.state = Object.assign({}, this.state, next);
      this.forceUpdate();
    }
    forceUpdate() { if (this.__mount) this.__mount(); }
  };

  window.dcLiteStart = function (Component, props) {
    const tpl = document.getElementById('dc-markup').content;
    const helmet = tpl.querySelector('helmet');
    if (helmet) helmet.childNodes.forEach((c) => document.head.appendChild(c.cloneNode(true)));
    const root = document.getElementById('dc-root');
    const comp = new Component(props || {});
    comp.__mount = () => {
      const frag = document.createDocumentFragment();
      const scope = comp.renderVals();
      tpl.childNodes.forEach((c) => render(c, scope, frag));
      root.replaceChildren(frag);
    };
    comp.__mount();
  };
})();
"""

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<!-- Generated by build_standalone.py from {source}. Edit the .dc.html and rebuild. -->
<style>html,body{{margin:0;background:#0F1326}}#dc-root{{display:flex;justify-content:center}}</style>
</head>
<body>
<div id="dc-root"></div>
<template id="dc-markup">
{markup}
</template>
<script>{runtime}</script>
<script>
{logic}
dcLiteStart(Component, {{}});
</script>
</body>
</html>
"""


def build(src: pathlib.Path) -> pathlib.Path:
    s = src.read_text()
    title = html.unescape(re.search(r'<title>(.*?)</title>', s, re.S).group(1).strip())
    markup = re.search(r'<x-dc>(.*)</x-dc>', s, re.S).group(1).strip()
    for blob, local in BLOBS.items():
        markup = markup.replace(blob, local)
    logic = re.search(r'<script type="text/x-dc"[^>]*>(.*?)</script>', s, re.S).group(1).strip()
    OUT.mkdir(exist_ok=True)
    stem = src.name.replace('.dc.html', '')
    dst = OUT / (NAMES.get(stem, stem.lower()) + '.html')
    dst.write_text(PAGE.format(title=title, source=src.name, markup=markup, runtime=DC_LITE, logic=logic))
    return dst


def main():
    names = sys.argv[1:] or sorted(p.name for p in HERE.glob('*.dc.html'))
    for name in names:
        print('built', build(HERE / name).relative_to(HERE))


if __name__ == '__main__':
    main()
